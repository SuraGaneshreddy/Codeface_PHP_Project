          <span class="solved-check" id="labStatus" <?= $done ? '' : 'hidden' ?>>✓ complete</span>
        </div>
        <div class="problem-meta-row">
          <span class="lab-kind lab-kind-<?= e($lab['kind']) ?>"><?= $lab['kind'] === 'debug' ? '🐞 legacy debug' : '🔌 API integration' ?></span>
          <span class="badge <?= difficulty_badge_class($lab['difficulty']) ?>"><?= e($lab['difficulty']) ?></span>
          <span class="muted">~<?= (int)$lab['minutes'] ?> min</span>
        </div>
        <div class="desc-body"><?= allow_html($lab['brief']) ?></div>

        <?php if ($isAiLab): ?>
        <div class="ai-hero"><span>🤖</span> This environment was generated by the Codeface AI for you — finish the whole set to unlock the next 10.</div>
        <?php endif; ?>

        <h4 class="tests-preview-title">Task checklist</h4>
        <ul class="task-list" id="labTasks"></ul>

        <div class="note-box">
