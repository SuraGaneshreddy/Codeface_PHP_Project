          nothing runs on the server. Files load in tab order; readonly files simulate a vendor/published API you cannot change.
        </div>
      </div>
    </section>

    <section class="pane pane-right">
      <div class="editor-toolbar">
        <span class="toolbar-note">multi-file project · JavaScript</span>
